/** Distance between cell centres in viewBox units. */
export const STEP = 4;
/** Cell size, matching the source pack's stroke-width. */
export const CELL = 4;
/** Centre of the first cell. */
export const ORIGIN = 3;
export const VIEWBOX = 30;

