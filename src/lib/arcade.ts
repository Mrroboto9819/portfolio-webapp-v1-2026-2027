export type ArcadeIcon = keyof typeof ARCADE;

/** Every name in the set — handy for an admin picker or a demo grid. */
export const ARCADE_NAMES = Object.keys(ARCADE) as ArcadeIcon[];

/** The mask for `name`, or an empty grid rather than a crash on a bad name. */
export function mask(name: ArcadeIcon | string): string {
	return (ARCADE as Record<string, string>)[name] ?? '0'.repeat(GRID * GRID);
}
