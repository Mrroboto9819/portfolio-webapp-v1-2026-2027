// The arcade icon set, as data.
//
// Every icon in static/icons/ui is 7x7 pixel art on one shared grid: a 30x30
// viewBox with a 4px square at each of x,y in {3,7,11,15,19,23,27}. The source
// files draw all 49 cells and hide the empty ones behind a transparent stroke,
// which makes them ~4 KB each and impossible to animate.
//
// Reduced to a 49-character mask, an icon is one string, and morphing between
// any two is a per-cell comparison — see PixelIcon.svelte. This is also why the
// set is not run through a morphing library: those interpolate outline PATHS
// between two shapes, and there is no outline here to interpolate. Two icons on
// an identical grid morph by flipping cells, which is both exact and the right
// look for pixel art.
//
// Read a mask row by row, top-left first: '1' is a lit cell, '0' is empty.

/** Cells per side. The viewBox is GRID * STEP + PAD * 2 = 30. */
